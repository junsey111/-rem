const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const { validAnnouncement } = require(path.join(root, 'third_party/billd-live-server/dist/service/announcement-content'));
const { RoomPresence } = require(path.join(root, 'third_party/billd-live-server/dist/service/room-presence'));
const image = '/platform-content/images/10000000-0000-4000-8000-000000000001';
const legacy = { title: '系统公告', body: '文字公告', published: true, published_at: '2026-11-12' };
const rich = { ...legacy, cover_path: image, blocks: [{ type: 'heading', level: 2, align: 'center', runs: [{ text: '新活动', bold: true }] }, { type: 'image', url: image }] };
assert(validAnnouncement(legacy)); assert(validAnnouncement(rich));
assert(validAnnouncement({ ...legacy, body: '', blocks: [{ type: 'image', url: image }] }));
assert(!validAnnouncement({ ...rich, cover_path: 'https://example.com/a.png' }));
assert(!validAnnouncement({ ...rich, blocks: [{ type: 'image', url: 'javascript:alert(1)' }] }));
assert(!validAnnouncement({ ...rich, blocks: [{ type: 'html', html: '<script>alert(1)</script>' }] }));
assert(!validAnnouncement({ ...rich, blocks: [{ type: 'paragraph', runs: [{ text: 'a', bold: 'true' }] }] }));
assert(!validAnnouncement({ ...rich, blocks: [{ type: 'paragraph', runs: [{ text: '字'.repeat(10001) }] }] }));
assert(!validAnnouncement({ ...legacy, blocks: [] }));
const presence = new RoomPresence();
presence.join('host', { roomId: '11', userId: 1, username: '主播', hostId: 1 });
presence.join('host-gifts', { roomId: '11', userId: 1, username: '主播', hostId: 1 });
presence.join('viewer-a', { roomId: '11', userId: 2, username: '用户', hostId: 1 });
presence.join('viewer-b', { roomId: '11', userId: 2, username: '用户', hostId: 1 });
assert.equal(presence.activity('11').viewer_count, 1); assert.equal(presence.activity('11').entries.length, 1);
presence.join('viewer-a', { roomId: '11', userId: 2, username: '用户', hostId: 1 });
assert.equal(presence.activity('11').entries.length, 1);
presence.leave('viewer-a'); assert.equal(presence.activity('11').viewer_count, 1);
presence.join('viewer-b', { roomId: '12', userId: 2, username: '用户', hostId: 3 });
assert.equal(presence.activity('11').viewer_count, 0); assert.equal(presence.activity('12').viewer_count, 1);
presence.leave('viewer-b'); assert.equal(presence.activity('12').entries.length, 0);
console.log('PASS announcement compatibility, document/image validation, distinct viewers, room switching and cleanup');
